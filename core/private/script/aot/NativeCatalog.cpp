std::span<const SferaNativeModule> SferaNativeCatalog::modules() { return nativeModules; }

const SferaNativeModule *SferaNativeCatalog::find(std::string_view name)
{
    const auto found = std::lower_bound(std::begin(nativeModules), std::end(nativeModules), name,
        [](const auto &module, auto key) { return compareModule(key, module.name) > 0; });
    return found != std::end(nativeModules) && compareModule(name, found->name) == 0 ? found : nullptr;
}

std::uint32_t SferaNativeCatalog::findSymbol(std::string_view name)
{
    const auto found = std::lower_bound(std::begin(symbols), std::end(symbols), name);
    return found != std::end(symbols) && *found == name ? static_cast<std::uint32_t>(found - std::begin(symbols) + 1) : 0u;
}

std::string_view SferaNativeCatalog::symbolName(std::uint32_t symbol)
{
    return symbol > 0 && symbol <= std::size(symbols) ? symbols[symbol - 1] : std::string_view{};
}

std::string_view SferaNativeCatalog::moduleName(std::uint32_t tag)
{
    const auto found = std::lower_bound(std::begin(tags), std::end(tags), tag,
        [](const auto &entry, auto value) { return entry.tag < value; });
    return found != std::end(tags) && found->tag == tag ? found->name : std::string_view{};
}

std::uint32_t SferaNativeCatalog::findModuleTag(std::string_view name)
{
    for (const auto &entry : tags)
        if (compareModule(name, entry.name) == 0)
            return entry.tag;
    return UINT32_MAX;
}

const SferaNativeObjectInitializer &SferaNativeCatalog::objectType(std::uint16_t type)
{
    if (type >= std::size(nativeObjectTypes))
        throw std::out_of_range("Invalid native object type");
    return nativeObjectTypes[type];
}
