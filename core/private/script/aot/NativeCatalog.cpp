int compareModule(std::string_view left, std::string_view right)
{
    for (std::size_t i = 0; i < std::min(left.size(), right.size()); ++i)
    {
        const auto byte = static_cast<unsigned char>(left[i]);
        const auto folded = byte >= 'A' && byte <= 'Z' ? byte + ('a' - 'A') : byte;
        if (folded != static_cast<unsigned char>(right[i]))
            return folded < static_cast<unsigned char>(right[i]) ? -1 : 1;
    }
    return left.size() == right.size() ? 0 : left.size() < right.size() ? -1 : 1;
}
